"""QR codes for camera pairing (Bit 13).

A printed or on-screen QR code lets a phone join a camera feed without typing
a URL: the code encodes a signed link to :func:`imani.routes.cameras.scan`,
which renders the phone capture page for that one camera.

The link carries a signed token (itsdangerous, using the app secret) rather
than a session, so a phone that has never signed in can still stream frames.
Tokens expire after ``QR_TOKEN_MAX_AGE`` seconds (30 days by default) and can
be regenerated by reloading the camera's QR page.
"""
from __future__ import annotations

import io
import socket

from flask import current_app, request

SALT = "imani-camera-qr"
CONNECT_SALT = "imani-device-connect"


def _serializer(salt: str = SALT):
    from itsdangerous import URLSafeTimedSerializer

    return URLSafeTimedSerializer(
        current_app.config["SECRET_KEY"], salt=salt,
    )


def make_token(camera_id: int) -> str:
    return _serializer().dumps({"camera_id": int(camera_id)})


def load_token(token: str) -> int | None:
    """Return the camera id carried by ``token``, or ``None`` if invalid."""
    from itsdangerous import BadSignature, SignatureExpired

    max_age = int(current_app.config.get("QR_TOKEN_MAX_AGE", 2592000))
    try:
        payload = _serializer().loads(token, max_age=max_age)
    except SignatureExpired:
        return None
    except BadSignature:
        return None
    except Exception:
        return None
    try:
        return int(payload.get("camera_id"))
    except (TypeError, ValueError):
        return None


def make_connect_token() -> str:
    """Create a short-lived token for the *self-registering* device QR.

    Unlike :func:`make_token`, this token is not tied to a camera yet. The
    phone that scans it registers a new phone camera on first open.
    """
    import secrets

    return _serializer(CONNECT_SALT).dumps({
        "connect": 1,
        "nonce": secrets.token_hex(8),
    })


def load_connect_token(token: str) -> dict | None:
    """Validate a device-connect token and return its payload."""
    from itsdangerous import BadSignature, SignatureExpired

    max_age = int(current_app.config.get("CONNECT_TOKEN_MAX_AGE", 3600))
    try:
        payload = _serializer(CONNECT_SALT).loads(token, max_age=max_age)
    except SignatureExpired:
        return None
    except BadSignature:
        return None
    except Exception:
        return None
    if not payload.get("connect") or not payload.get("nonce"):
        return None
    return payload


def connect_device_url(token: str) -> str:
    return f"{public_base_url()}/cameras/connect/{token}"


def lan_ip() -> str | None:
    """Best guess at this machine's LAN address (no traffic is sent)."""
    try:
        probe = socket.socket(socket.AF_INET, socket.SOCK_DGRAM)
        try:
            probe.connect(("8.8.8.8", 80))
            return probe.getsockname()[0]
        finally:
            probe.close()
    except Exception:
        pass
    try:
        return socket.gethostbyname(socket.gethostname())
    except Exception:
        return None


def public_base_url() -> str:
    """The base URL a phone on the same network can reach.

    When the console is opened on ``127.0.0.1`` the host is swapped for the
    machine's LAN IP, otherwise the QR would be useless to a phone.

    Operators can override the advertised URL (for a tunnel, reverse proxy or
    DNS name) with ``IMANI_PUBLIC_URL``; ``IMANI_PUBLIC_SCHEME`` and
    ``IMANI_PUBLIC_PORT`` override only those parts.
    """
    override = (current_app.config.get("PUBLIC_BASE_URL") or "").strip()
    if override:
        return override.rstrip("/")

    root = request.url_root.rstrip("/")
    host = (request.host or "").split(":")[0]
    if host in ("localhost", "127.0.0.1", "0.0.0.0", "::1"):
        address = lan_ip()
        if address:
            scheme = request.scheme or "http"
            port = ""
            if ":" in (request.host or ""):
                port = ":" + request.host.split(":")[-1]
            root = f"{scheme}://{address}{port}"

    scheme_override = (current_app.config.get("PUBLIC_SCHEME") or "").strip()
    port_override = str(current_app.config.get("PUBLIC_PORT") or "").strip()
    if scheme_override or port_override:
        from urllib.parse import urlsplit, urlunsplit

        parts = urlsplit(root)
        scheme = scheme_override or parts.scheme
        netloc = parts.hostname or ""
        port = port_override or (str(parts.port) if parts.port else "")
        if port:
            netloc = f"{netloc}:{port}"
        root = urlunsplit((scheme, netloc, parts.path, "", ""))
    return root


def scan_url(camera_id: int) -> str:
    token = make_token(camera_id)
    return f"{public_base_url()}/cameras/scan/{token}"


def png(data: str) -> bytes:
    """Render ``data`` (a URL) as a PNG QR code."""
    import qrcode
    from qrcode.constants import ERROR_CORRECT_M

    code = qrcode.QRCode(
        version=None,
        error_correction=ERROR_CORRECT_M,
        box_size=8,
        border=2,
    )
    code.add_data(data)
    code.make(fit=True)
    image = code.make_image(fill_color="#2a1547", back_color="white").convert("RGB")
    buffer = io.BytesIO()
    image.save(buffer, format="PNG")
    return buffer.getvalue()
